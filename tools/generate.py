#!/usr/bin/env python3
"""Regenerate the engine-derived sections of the specification.

Anything this script writes is a function of the reference implementation, so the
published spec cannot claim a keyword, an operator, an error code or a stdlib
signature the engine does not have. Prose chapters (00, 02, 03, 04) are authored by
hand and never touched here.

    python3 tools/generate.py --engine /home/aamir/tallowsphere
"""
from __future__ import annotations

import argparse
import glob
import json
import re
import subprocess
from pathlib import Path

HEADER = ("<!-- generated by tools/generate.py from {sha} ({date}); do not edit by hand -->\n"
          "<!-- regenerate: python3 tools/generate.py --engine <tallowsphere> -->\n\n")


def git_sha(engine: Path) -> str:
    try:
        return subprocess.run(["git", "-C", str(engine), "rev-parse", "--short", "HEAD"],
                              capture_output=True, text=True, check=True).stdout.strip()
    except Exception:
        return "unknown"


def keywords(engine: Path) -> list[tuple[str, str]]:
    src = (engine / "src/lexer.rs").read_text()
    start = src.index('"let" => TokenKind::Let')
    end = src.index("}", start)
    block = src[start:end]
    out = []
    for word, tok in re.findall(r'"([a-z_][a-z0-9_]*)"\s*=>\s*TokenKind::(\w+)', block):
        out.append((word, tok))
    # `_` is matched separately in the lexer, not through the keyword table.
    out.append(("_", "Underscore"))
    return out


def tokens(engine: Path) -> list[tuple[str, str]]:
    """Operator/punctuation table straight from the TokenKind variants and their comments."""
    src = (engine / "src/lexer.rs").read_text()
    body = src[src.index("pub enum TokenKind {"):]
    body = body[:body.index("\n}")]
    out, section = [], ""
    for line in body.splitlines():
        m = re.match(r"\s*//\s*──\s*(.+?)\s*──", line)
        if m:
            section = m.group(1)
            continue
        m = re.match(r"\s*([A-Z]\w*)(?:\([^)]*\))?,\s*//\s*(.+)$", line)
        if m and section in ("Operators", "Delimiters", "Punctuation"):
            out.append((m.group(2).strip().rstrip("."), f"{m.group(1)} (`{section}`)"))
    return out


def error_codes(engine: Path) -> list[tuple[str, str]]:
    """(code, emitting file). Messages are deliberately NOT extracted.

    A diagnostic message is assembled at runtime from a format string plus call-site
    arguments; guessing the pairing from source order produced nonsense (codes paired
    with the next unrelated literal), so the catalogue records what is actually stable
    — the code and the pass that emits it — and the prose shows a real message taken
    from a real run.
    """
    seen: dict[str, str] = {}
    for path in sorted(glob.glob(str(engine / "src/**/*.rs"), recursive=True)):
        text = Path(path).read_text(errors="ignore")
        for m in re.finditer(r'"(E\d{4})"', text):
            seen.setdefault(m.group(1), Path(path).name)
    return sorted(seen.items())


def stdlib(engine: Path) -> list[dict]:
    mods = []
    for path in sorted(glob.glob(str(engine / "stdlib/*.tl"))):
        text = Path(path).read_text()
        doc: list[str] = []
        module = Path(path).stem
        fns = []
        pending: list[str] = []
        for line in text.splitlines():
            s = line.strip()
            if s.startswith("///"):
                pending.append(s[3:].strip())
                continue
            m = re.match(r"module\s+([\w.]+)", s)
            if m:
                module = m.group(1)
                doc = pending
                pending = []
                continue
            m = re.match(r"(?:native\s+)?fn\s+([a-z_]\w*)\s*\((.*)\)\s*(?:->\s*(.+?))?\s*$", s)
            if m:
                fns.append({"name": m.group(1), "sig": s.split("fn", 1)[1].strip(), "doc": " ".join(pending)})
                pending = []
                continue
            if s and not s.startswith("//"):
                pending = []
        mods.append({"module": module, "doc": " ".join(doc), "fns": fns})
    return mods


def write_lexical(out: Path, sha: str, date: str, kws, toks):
    lines = [HEADER.format(sha=sha, date=date), "# 1. Lexical structure\n",
             "## 1.1 Keywords\n",
             "These are the reserved words of the language. They are recognised by the lexer and",
             "cannot be used as identifiers. `_` is reserved as a pattern wildcard.\n",
             "| Keyword | Token |", "|---|---|"]
    lines += [f"| `{w}` | `{t}` |" for w, t in kws]
    lines += ["", "## 1.2 Operators and punctuation\n",
              "| Spelling | Token |", "|---|---|"]
    lines += [f"| `{s}` | {t} |" for s, t in toks]
    lines += ["", "## 1.3 Literals\n",
              "- **Int**: decimal digits, with `_` separators; an `i128` internally.",
              "- **Float**: digits with a `.` and/or exponent; `f64`.",
              "- **String**: double-quoted, with `\\n`, `\\t`, `\\r`, `\\\\`, `\\\"`, `\\0`, `\\xHH` escapes.",
              "- **Interpolated string**: `\"text {expr} more\"` compiles to StringStart/StringMid/StringEnd",
              "  tokens; the lexer, not the parser, splits it.",
              "- **Bool**: `true`, `false`. **Nil**: `nil`.",
              "- Comments: `//` to end of line, `/* … */` block. Doc comments are `///`.\n"]
    (out / "01-lexical.md").write_text("\n".join(lines) + "\n")


def write_errors(out: Path, sha: str, date: str, codes):
    lines = [HEADER.format(sha=sha, date=date), "# 5. Error catalogue\n",
             f"Every diagnostic code the reference implementation emits ({len(codes)} codes), with the",
             "pass that raises it. The **code** is part of the specification — tooling may match on it.",
             "The **message** is not: it is assembled at runtime and may be reworded in any release.\n",
             "| Code | Emitted by |", "|---|---|"]
    for code, file in codes:
        lines.append(f"| `{code}` | `{file}` |")
    (out / "05-errors.md").write_text("\n".join(lines) + "\n")
    return len(codes)


def write_stdlib(out: Path, sha: str, date: str, mods):
    total = sum(len(m["fns"]) for m in mods)
    lines = [HEADER.format(sha=sha, date=date), "# 6. Standard library index\n",
             f"{len(mods)} modules, {total} functions. Signatures are the contract; behaviour notes are",
             "the module's own documentation. I/O modules are engine surfaces — see the note in the README.\n",
             "## Modules\n"]
    for m in mods:
        lines.append(f"- [`{m['module']}`](#{m['module'].replace('.', '').replace('_', '-')}) — {m['doc'][:90]}")
    for m in mods:
        slug = m["module"].replace(".", "-").replace("_", "-")
        lines += ["", f'<a id="{slug}"></a>', f"## `{m['module']}`\n"]
        if m["doc"]:
            lines += [m["doc"], ""]
        if not m["fns"]:
            lines += ["_No functions declared._", ""]
            continue
        lines += ["```tallow"] + [f"fn {f['sig']}" for f in m["fns"]] + ["```", ""]
        for f in m["fns"]:
            if f["doc"]:
                lines.append(f"- `{f['name']}` — {f['doc']}")
        lines.append("")
    (out / "06-stdlib.md").write_text("\n".join(lines) + "\n")
    return len(mods), total


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--engine", required=True)
    ap.add_argument("--repo", default=str(Path(__file__).resolve().parent.parent))
    a = ap.parse_args()
    engine, repo = Path(a.engine), Path(a.repo)
    out = repo / "spec"
    out.mkdir(parents=True, exist_ok=True)
    sha = git_sha(engine)
    date = subprocess.run(["date", "-u", "+%Y-%m-%d"], capture_output=True, text=True).stdout.strip()

    kws, toks = keywords(engine), tokens(engine)
    codes = error_codes(engine)
    mods = stdlib(engine)
    write_lexical(out, sha, date, kws, toks)
    n_codes = write_errors(out, sha, date, codes)
    n_mods, n_fns = write_stdlib(out, sha, date, mods)

    (repo / "spec" / "generated.json").write_text(json.dumps(
        {"engine_sha": sha, "generated": date, "keywords": len(kws), "tokens": len(toks),
         "error_codes": n_codes, "stdlib_modules": n_mods, "stdlib_fns": n_fns}, indent=2))
    print(f"engine {sha}: {len(kws)} keywords, {len(toks)} tokens, {n_codes} error codes, "
          f"{n_mods} stdlib modules / {n_fns} functions")


if __name__ == "__main__":
    main()
